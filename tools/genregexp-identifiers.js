#!/usr/bin/env node
// Generate the RegExp parser's identifier tables from the pinned ICU data.
const fs = require("node:fs");
const path = require("node:path");

const nodeVersion = "24.19.0";
const icuVersion = "78.3";
const unicodeVersion = "17.0";
if (
  process.versions.node !== nodeVersion ||
  process.versions.icu !== icuVersion ||
  process.versions.unicode !== unicodeVersion
) {
  throw new Error(
    `expected Node ${nodeVersion}/ICU ${icuVersion}/Unicode ${unicodeVersion}; got Node ${process.versions.node}/ICU ${process.versions.icu}/Unicode ${process.versions.unicode}`,
  );
}

const root = path.resolve(__dirname, "..");
const outputPath = path.join(
  root,
  "tsc/internal/regexpengine/regexp_unicode_identifiers.go",
);

function propertyRanges(property) {
  const matcher = new RegExp(`^\\p{${property}}$`, "u");
  const ranges = [];
  let start = -1;
  let end = -1;
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint++) {
    if (matcher.test(String.fromCodePoint(codePoint))) {
      if (start < 0) start = codePoint;
      end = codePoint;
    } else if (start >= 0) {
      ranges.push([start, end]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, end]);
  return ranges;
}

function goRanges(ranges) {
  return ranges
    .map(([start, end]) => `\t{0x${start.toString(16)}, 0x${end.toString(16)}},`)
    .join("\n");
}

const lines = [
  "// Code generated by tools/genregexp-identifiers.js; DO NOT EDIT.",
  "// Derived from ICU 78.3 / Unicode 17.0 ID_Start and ID_Continue properties.",
  "// Unicode data is subject to the Unicode Terms of Use.",
  "package regexpengine",
  "",
  'const regexpUnicodeIdentifierDataVersion = "17.0.0"',
  "",
  "var regexpUnicodeIdentifierStartRanges = []classRange{",
  goRanges(propertyRanges("ID_Start")),
  "}",
  "",
  "var regexpUnicodeIdentifierContinueRanges = []classRange{",
  goRanges(propertyRanges("ID_Continue")),
  "}",
  "",
];
fs.writeFileSync(outputPath, lines.join("\n"));
