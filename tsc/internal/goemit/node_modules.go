package goemit

import (
	"strconv"
	"strings"

	"github.com/microsoft/TypeScript/tsc/internal/ast"
)

// IsNativeNodeModule is shared with the bundler so built-ins do not masquerade
// as unresolved source modules or force a single-file program into a bundle.
func IsNativeNodeModule(name string) bool {
	switch strings.TrimPrefix(name, "node:") {
	case "fs", "fs/promises", "buffer":
		return true
	}
	return false
}

func (b *machineBuilder) nodeImport(node *ast.Node) bool {
	n := node.AsImportDeclaration()
	name := strings.TrimPrefix(n.ModuleSpecifier.Text(), "node:")
	if !IsNativeNodeModule(name) {
		return false
	}
	if n.ImportClause == nil {
		return true
	}
	c := n.ImportClause.AsImportClause()
	if c.PhaseModifier == ast.KindTypeKeyword {
		return true
	}
	prefix := "node-module|" + name + "|"
	if c.Name() != nil {
		b.e.imports[n.ImportClause] = prefix
	}
	if c.NamedBindings != nil {
		if c.NamedBindings.Kind == ast.KindNamespaceImport {
			b.e.imports[c.NamedBindings] = prefix
		} else {
			for _, specifier := range c.NamedBindings.AsNamedImports().Elements.Nodes {
				s := specifier.AsImportSpecifier()
				if s.IsTypeOnly {
					continue
				}
				key := specifier.Name().Text()
				if s.PropertyName != nil {
					key = s.PropertyName.Text()
				}
				b.e.imports[specifier] = prefix + key
			}
		}
	}
	return true
}

func (b *machineBuilder) nodeImportEquals(node *ast.Node) {
	n := node.AsImportEqualsDeclaration()
	if n.IsTypeOnly {
		return
	}
	reference := n.ModuleReference
	if reference.Kind != ast.KindExternalModuleReference {
		b.e.fail(node, "only external import-equals is supported")
		return
	}
	name := reference.AsExternalModuleReference().Expression.Text()
	if !IsNativeNodeModule(name) {
		b.e.fail(node, "unresolved import "+name)
		return
	}
	b.e.imports[node] = "node-module|" + strings.TrimPrefix(name, "node:") + "|"
}

func (b *machineBuilder) nodeModuleCall(node *ast.Node) (string, bool) {
	call := node.AsCallExpression()
	require := call.Expression.Kind == ast.KindIdentifier && call.Expression.Text() == "require" && b.e.binding(call.Expression) == nil
	dynamic := call.Expression.Kind == ast.KindImportKeyword
	if !require && !dynamic {
		return "", false
	}
	if len(call.Arguments.Nodes) != 1 || call.Arguments.Nodes[0].Kind != ast.KindStringLiteral {
		return "", false
	}
	name := strings.TrimPrefix(call.Arguments.Nodes[0].Text(), "node:")
	if !IsNativeNodeModule(name) {
		return "", false
	}
	expression := "tsNodeModule(" + strconv.Quote(name) + ")"
	if dynamic {
		expression = "loop.resolved(tsNodeModuleNamespace(" + strconv.Quote(name) + "),false)"
	}
	return b.temp(expression), true
}

